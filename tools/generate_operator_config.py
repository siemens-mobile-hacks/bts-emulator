#!/usr/bin/env python3
"""Generate the operator proxy and MMSC lists in config/ from operators.csv.

Writes into config/ or OUTPUT_DIR:
  operator-proxies.nft       nftables defines OPERATOR_PROXIES and OPERATOR_MMSCS with proxy and MMSC IPv4 addresses
  operator-proxy-hosts.txt   proxy host names, one per line
  operator-mmsc-domains.txt  MMSC host names, one per line
  operator-mmsc-ips.txt      MMSC IPv4 addresses, one per line

Usage: generate_operator_config.py [-i operators.csv] [OUTPUT_DIR]
"""

import argparse
import csv
import ipaddress
import pathlib
import re
from urllib.parse import urlsplit

HOST_NAME = re.compile(r"[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*")
ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT / "operators.csv"
DEFAULT_OUTPUT = ROOT / "config"


def proxy_host(proxy):
    host, _, port = proxy.rpartition(":")
    if not port.isdigit():
        raise ValueError(f"bad proxy {proxy!r}")
    return host.lower()


def mmsc_host(url):
    host = urlsplit(url).hostname
    if not host:
        raise ValueError(f"bad MMSC URL {url!r}")
    return host


def is_ipv4(host):
    try:
        ipaddress.IPv4Address(host)
    except ValueError:
        return False
    return True


def read_profiles(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def collect(profiles):
    proxy_ips, proxy_names = set(), set()
    mmsc_ips, mmsc_names = set(), set()
    for profile in profiles:
        hosts = [(proxy_host(profile["proxy"]), proxy_ips, proxy_names)] if profile["proxy"] else []
        hosts += [(mmsc_host(url), mmsc_ips, mmsc_names) for url in profile["mmsc"].split()]
        for host, ips, names in hosts:
            if is_ipv4(host):
                ips.add(ipaddress.IPv4Address(host))
            elif HOST_NAME.fullmatch(host):
                names.add(host)
            else:
                raise ValueError(f"bad host {host!r}")
    proxy_ips.discard(ipaddress.IPv4Address("0.0.0.0"))
    return sorted(proxy_ips), sorted(proxy_names), sorted(mmsc_ips), sorted(mmsc_names)


def nft_define(name, ips):
    elements = ",\n".join(f"\t{ip}" for ip in ips)
    return f"define {name} = {{\n{elements}\n}}\n"


def write_lines(path, header, lines):
    path.write_text("".join(f"# {line}\n" for line in header) + "".join(f"{line}\n" for line in lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("-i", "--input", type=pathlib.Path, default=DEFAULT_INPUT)
    parser.add_argument("output_dir", type=pathlib.Path, nargs="?", default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    proxy_ips, proxy_names, mmsc_ips, mmsc_names = collect(read_profiles(args.input))
    header = [f"Generated by {pathlib.Path(__file__).name} from {args.input.name}. Do not edit."]

    (args.output_dir / "operator-proxies.nft").write_text(
        f"# {header[0]}\n\n{nft_define('OPERATOR_PROXIES', proxy_ips)}\n{nft_define('OPERATOR_MMSCS', mmsc_ips)}"
    )
    write_lines(args.output_dir / "operator-proxy-hosts.txt", header, proxy_names)
    write_lines(args.output_dir / "operator-mmsc-domains.txt", header, mmsc_names)
    write_lines(args.output_dir / "operator-mmsc-ips.txt", header, mmsc_ips)
    print(f"proxies: {len(proxy_ips)} addresses, {len(proxy_names)} names; "
          f"MMSC: {len(mmsc_ips)} addresses, {len(mmsc_names)} names")


if __name__ == "__main__":
    main()
